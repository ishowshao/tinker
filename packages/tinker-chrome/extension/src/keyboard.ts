function requireValidKey(key: string): KeyInput {
  if (!VALID_KEYS.has(key)) {
    throw new Error(`${key} is not a supported Puppeteer key.`);
  }
  return key as KeyInput;
}

export function parseKey(keyInput: string): [KeyInput, ...KeyInput[]] {
  let key = "";
  const result: KeyInput[] = [];
  for (const character of keyInput) {
    if (character === "+" && key !== "") {
      result.push(requireValidKey(key));
      key = "";
    } else {
      key += character;
    }
  }
  if (key !== "") {
    result.push(requireValidKey(key));
  }
  if (result.length === 0) {
    throw new Error(`Key ${keyInput} could not be parsed.`);
  }
  if (new Set(result).size !== result.length) {
    throw new Error(`Key ${keyInput} contains duplicate keys.`);
  }
  const primary = result.at(-1);
  if (primary === undefined || MODIFIERS.has(primary)) {
    throw new Error(`Key ${keyInput} must end in a non-modifier key.`);
  }
  const modifiers = result.slice(0, -1);
  const invalidModifier = modifiers.find((modifier) => !MODIFIERS.has(modifier));
  if (invalidModifier !== undefined) {
    throw new Error(`${invalidModifier} is not a supported modifier.`);
  }
  return [primary, ...modifiers];
}
